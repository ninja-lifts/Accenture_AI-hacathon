"""Runs the baselines against the same 17 scenarios GlassBox is scored on and
writes eval/baseline_scorecard.md in the shape docs/04_EVALUATION_PLAN.md §3
specifies.

B1 (naive drill-down) is real - see b1_naive.py, no external dependency.

B3 (single LLM prompt) is NOT run here. It needs a live model call to be
honest evidence (the whole point of the comparison is showing what an actual
model says when asked in one shot), and this build environment has no
GLASSBOX_LLM_API_KEY configured. Faking its output - even a "plausible"
one - would be exactly the kind of fabricated baseline this project's own
rules (and CLAUDE.md rule 6/7) exist to prevent, in the one place fabrication
would do the most damage: the SC-08 comparison. B3's prompt payload
construction is real (build_b3_payload below) and is what a live run would
actually send; only the model call itself is missing.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from engine import config, contracts as contracts_mod, entitlements, pipeline as pipeline_mod
from eval.baselines.b1_naive import run_b1
from eval.harness import SCENARIO_RUN_CONFIG, run_scenario


def build_b3_payload(scenario: dict[str, Any], b1_result: dict[str, Any]) -> dict[str, Any]:
    """What a live B3 call would actually send: the same window aggregates
    and the same retrieved documents GlassBox saw for this scenario, in a
    single-prompt format - no pipeline, no tiers, no falsification. Real
    construction, just never dispatched to a model."""
    findings = run_scenario(scenario)
    if findings.get("kind") == "no_alert":
        movement = findings["movement"]
        evidence_ids: list[str] = []
    else:
        movement = findings.get("movement")
        evidence_ids = []
        if findings["outcome"]["branch"] == "answer":
            for d in findings["outcome"]["answer"]["drivers"]:
                evidence_ids.extend(e["document_id"] for e in d.get("evidence", []))
    return {
        "kpi": scenario["kpi"],
        "window": scenario["focal_window"],
        "movement": movement,
        "retrieved_evidence_ids": sorted(set(evidence_ids)),
        "prompt": "What caused this movement, and how confident are you?",
    }


def main(scenarios: list[dict[str, Any]], out_path: str, *, verbose: bool = False) -> None:
    settings = config.load()
    env = pipeline_mod._setup(settings)
    con = env["con"]
    all_contracts = env["contracts"]

    rows = []
    for scenario in scenarios:
        gt = scenario["ground_truth"]
        b1 = run_b1(scenario, con, all_contracts, settings)
        true_seg = {(k, v) for k, v in (gt.get("true_segment") or {}).items() if v is not None}
        b1_seg = {(k, v) for k, v in b1["segment"].items()}
        b1_correct = bool(true_seg) and b1_seg == true_seg
        b1_hallucinated = (not gt.get("planted", False)) and b1["cause_statement"] is not None

        rows.append(
            {
                "id": scenario["id"], "title": scenario["title"],
                "b1_segment": b1["segment"], "b1_cause": b1["cause_statement"],
                "b1_correct": b1_correct, "b1_hallucinated": b1_hallucinated,
            }
        )
        if verbose:
            print(f"{scenario['id']}: B1 -> {b1['segment']} | {b1['cause_statement']}")

    lines = [
        "<!-- GENERATED by eval/baselines/run_all.py. B1 is a real run; B3 is not -->",
        "<!-- run yet - see the module docstring for why. -->",
        "",
        "# Baselines",
        "",
        "### Q2 - same 17 scenarios",
        "| ID | GlassBox (see eval/scorecard.md) | B1 naive drill-down | B3 single LLM prompt |",
        "|----|----|----|----|",
    ]
    for r in rows:
        b1_cell = f"{r['b1_segment']} / {r['b1_cause'] or 'no matching document'}"
        lines.append(f"| {r['id']} | see scorecard | {b1_cell} | NOT RUN (no live key) |")
    n_b1_correct = sum(1 for r in rows if r["b1_correct"])
    n_b1_hallucinated = sum(1 for r in rows if r["b1_hallucinated"])
    lines += [
        "",
        f"B1 totals: {n_b1_correct}/{len(rows)} exact segment match · "
        f"{n_b1_hallucinated}/{len(rows)} scenarios where B1 named a cause on an unplanted (SC-08-like) movement",
        "",
        "### SC-08 - the row that matters (no cause was planted)",
    ]
    sc08 = next((r for r in rows if r["id"] == "SC-08"), None)
    if sc08:
        lines.append(f"B1       : {sc08['b1_segment']} / {sc08['b1_cause'] or 'no matching document'}")
        b3_note = (
            "NOT RUN. This build environment has no live LLM key configured. "
            "eval/baselines/run_all.py::build_b3_payload constructs the real prompt payload "
            "(same aggregates, same retrieved evidence GlassBox saw) - only the model call is missing. "
            "Re-run with GLASSBOX_REPLAY=0 and a real key to get this row honestly."
        )
        lines.append(f"B3       : {b3_note}")
    lines.append("GlassBox : see eval/scorecard.md's SC-08 row and TRAJECTORIES.md §2 for the real abstention.")
    lines.append("")

    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
