"""python -m eval.trace SC-01 [--out path.md]

The `--trace` capability from docs/01_MASTER_BUILD_FLOW.md's Phase 4, built
after the fact: TRAJECTORIES.md's SC-01/SC-08/SC-14 write-ups were captured
by hand, instrumenting the stage functions directly in a Python shell. This
automates that same capture for any scenario in the manifest - real stage-
by-stage context, not a hand-transcribed summary - without replacing
TRAJECTORIES.md's curated, annotated prose.

Uses `engine.pipeline.run(..., trace=True)`, which is additive: every other
caller of `pipeline.run` is unaffected."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import yaml

from engine import pipeline
from eval.harness import SCENARIO_RUN_CONFIG, TODAY, _window_for

_STAGE_TITLES = {
    "s00_intent": "00 — Intent",
    "s01_define": "01 — Define",
    "s02_detect": "02 — Detect",
    "s03_localize": "03 — Localize",
    "s04_decompose": "04 — Decompose",
    "s05_retrieve": "05 — Retrieve",
    "s06_falsify": "06 — Falsify",
    "s07_narrate": "07 — Narrate / Gate",
}


def run_traced(scenario: dict[str, Any]) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    sid = scenario["id"]
    config = dict(SCENARIO_RUN_CONFIG[sid])
    if config.get("trigger") != "user_question":
        config["window"] = _window_for(scenario)
    return pipeline.run(today=TODAY, trace=True, **config)


def render_trace(scenario: dict[str, Any], result: dict[str, Any], trace_log: list[dict[str, Any]]) -> str:
    sid = scenario["id"]
    lines = [
        f"# Trace — {sid}: {scenario['title']}", "",
        f"Difficulty: {scenario['difficulty']} · Expected branch: {scenario['expected_branch']}",
        "",
        "Generated by `python -m eval.trace` from a live run against the "
        "committed dataset - every value below is read directly off the "
        "pipeline's own context after each stage ran.",
        "",
    ]
    for entry in trace_log:
        stage = entry["stage"]
        lines.append(f"## Stage {_STAGE_TITLES.get(stage, stage)}")
        lines.append("```json")
        lines.append(json.dumps(entry["ctx"], indent=2, default=str, ensure_ascii=False))
        lines.append("```")
        lines.append("")

    if result.get("kind") == "no_alert":
        lines.append("## Result: no_alert (did not escalate past Stage 02)")
    else:
        lines.append(f"## Result: {result.get('outcome', {}).get('branch', 'unknown')}")
    lines.append("```json")
    dump = json.dumps(result, indent=2, default=str, ensure_ascii=False)
    lines.append(dump if len(dump) <= 20000 else dump[:20000] + "\n... (truncated)")
    lines.append("```")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("scenario_id", help="e.g. SC-01")
    parser.add_argument("--out", default=None, help="default: eval/traces/<scenario_id>.md")
    args = parser.parse_args()

    manifest = yaml.safe_load(Path("data/injection_manifest.yaml").read_text(encoding="utf-8"))
    scenario = next((s for s in manifest["scenarios"] if s["id"] == args.scenario_id), None)
    if scenario is None:
        raise SystemExit(f"no scenario '{args.scenario_id}' in data/injection_manifest.yaml")

    result, trace_log = run_traced(scenario)
    md = render_trace(scenario, result, trace_log)

    out = Path(args.out or f"eval/traces/{args.scenario_id}.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
